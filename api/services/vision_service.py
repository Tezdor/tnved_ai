# ============================================================
# MIME TYPE
# ============================================================

def get_image_mime(image_bytes):

    kind = imghdr.what(
        None,
        h=image_bytes
    )

    if kind == "png":
        return "image/png"

    if kind == "webp":
        return "image/webp"

    if kind == "gif":
        return "image/gif"

    return "image/jpeg"


# ============================================================
# IMAGE -> DATA URL
# ============================================================

def build_image_content_from_bytes(image_bytes):

    if not image_bytes:
        raise Exception(
            "Empty image bytes"
        )

    mime = get_image_mime(
        image_bytes
    )

    image_base64 = base64.b64encode(
        image_bytes
    ).decode("utf-8")

    return {
        "type": "image_url",
        "image_url": {
            "url": (
                f"data:{mime};base64,"
                f"{image_base64}"
            )
        }
    }


