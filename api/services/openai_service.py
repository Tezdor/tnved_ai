def get_preview_path(vision_data):

    preview = (
        vision_data
        .get("preview")
    )


    if not preview:

        print(
            "OPENAI: preview отсутствует"
        )

        return None


    print(
        "OPENAI PREVIEW:",
        preview
    )


    # --------------------------------------------------------
    # preview обычно выглядит:
    #
    # /media/products/xxxxx.webp
    #
    # Нам нужно:
    #
    # MEDIA_ROOT/products/xxxxx.webp
    # --------------------------------------------------------

    preview = str(
        preview
    ).replace(
        "\\",
        "/"
    )


    media_url = str(
        settings.MEDIA_URL
    ).replace(
        "\\",
        "/"
    )


    if preview.startswith(
        media_url
    ):

        relative_path = (
            preview[
                len(media_url):
            ]
            .lstrip("/")
        )

    else:

        relative_path = (
            preview
            .lstrip("/")
        )


    image_path = (
        Path(
            settings.MEDIA_ROOT
        )
        / relative_path
    )


    print(
        "OPENAI IMAGE PATH:",
        image_path
    )


    return image_path


