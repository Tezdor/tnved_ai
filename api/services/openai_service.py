def image_to_data_url(image_path):

    if not image_path:
        return None


    image_path = Path(image_path)


    if not image_path.exists():

        print(
            "OPENAI IMAGE NOT FOUND:",
            image_path
        )

        return None


    # Определяем MIME
    suffix = image_path.suffix.lower()

    mime_types = {
        ".jpg": "image/jpeg",
        ".jpeg": "image/jpeg",
        ".png": "image/png",
        ".webp": "image/webp",
        ".gif": "image/gif",
    }

    mime_type = mime_types.get(
        suffix,
        "image/webp"
    )


    try:

        with open(
            image_path,
            "rb"
        ) as image_file:

            image_bytes = (
                image_file.read()
            )


        if not image_bytes:

            print(
                "OPENAI IMAGE IS EMPTY:",
                image_path
            )

            return None


        encoded = base64.b64encode(
            image_bytes
        ).decode("utf-8")


        return (
            f"data:{mime_type};base64,{encoded}"
        )


    except Exception as e:

        print(
            "OPENAI IMAGE READ ERROR:",
            e
        )

        return None


